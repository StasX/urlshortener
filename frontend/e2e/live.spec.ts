import { expect, test } from '@playwright/test'

test('real browser, Vue, Gunicorn, JWT cookies and MongoDB work together', async ({ page, context, baseURL }) => {
  const email = `browser-${Date.now()}@example.com`
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Long links. Short stories.' })).toBeVisible()
  await page.screenshot({ path: 'test-results/shorty-home.png', fullPage: true })
  await page.getByLabel('Your destination URL').fill('https://example.com/guest')
  await page.getByRole('button', { name: 'Create short link' }).click()
  await expect(page.locator('output a')).toBeVisible()
  const guestLink = await page.locator('output a').getAttribute('href')
  expect((await context.request.get(guestLink!, { maxRedirects: 0 })).status()).toBe(302)

  await page.getByRole('link', { name: 'Get started' }).click()
  await page.getByLabel('First name').fill('Browser')
  await page.getByLabel('Last name').fill('Tester')
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('test-browser-password')
  await page.getByLabel('Repeat password').fill('test-browser-password')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText('Hi, Browser')).toBeVisible()
  const cookies = await context.cookies(`${baseURL}/api/`)
  expect(cookies.find(cookie => cookie.name === 'access_token_cookie')?.httpOnly).toBe(true)
  expect(await page.evaluate(() => document.cookie.includes('access_token_cookie'))).toBe(false)
  expect(await page.evaluate(() => Object.keys(localStorage).length)).toBe(0)

  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByText('No links yet.', { exact: false })).toBeVisible()
  await page.getByLabel('Your destination URL').fill('https://example.com/member')
  await page.getByRole('button', { name: 'Create short link' }).click()
  await expect(page.locator('output a')).toBeVisible()
  const memberLink = await page.locator('output a').getAttribute('href')
  expect((await context.request.get(memberLink!, { maxRedirects: 0 })).status()).toBe(302)
  await expect(page.locator('#urlsContainer article')).toHaveCount(1)
  await expect(page.locator('#urlsContainer article')).toContainText('Visits: 1')
  await expect(page.getByText('https://example.com/member', { exact: false })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Visits per short link' })).toBeVisible()
  await page.screenshot({ path: 'test-results/shorty-dashboard.png', fullPage: true })
  await page.reload()
  await expect(page.getByText('Hi, Browser')).toBeVisible()
  await expect(page.locator('#urlsContainer article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Remove link' }).click()
  await expect(page.getByText('No links yet.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Get started' })).toBeVisible()
  expect((await context.request.get(`${baseURL}/api/links`)).status()).toBe(401)
  await page.getByRole('link', { name: 'Sign in', exact: true }).first().click()
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('test-browser-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByText('Hi, Browser')).toBeVisible()
})
